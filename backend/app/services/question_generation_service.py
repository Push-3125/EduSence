# ---------------------------------------------------------------------------
# Domain Exceptions
# ---------------------------------------------------------------------------


class QuestionServiceError(Exception):
    """Base exception for question service errors."""


class QuestionBankNotFoundError(QuestionServiceError):
    """Raised when target question bank does not exist or user lacks ownership."""


class QuestionNotFoundError(QuestionServiceError):
    """Raised when target question does not exist or user lacks ownership."""


class InvalidQuestionConfigError(QuestionServiceError):
    """Raised when question generation parameters or question fields are invalid."""


class DocumentNotFoundError(QuestionServiceError):
    """Raised when target document does not exist or user lacks ownership."""


class EmptyDocumentError(QuestionServiceError):
    """Raised when target document has no text chunks available."""


# ---------------------------------------------------------------------------
# Structured LLM Output Schemas
# ---------------------------------------------------------------------------


class GeneratedQuestionItem(BaseModel):
    """Single question generated by Gemini structured output."""

    question_type: str = Field(
        default="multiple_choice",
        description="Question type: 'multiple_choice' or 'essay'",
    )
    content: str = Field(
        ...,
        description="Clear, rigorous academic question prompt or problem statement",
    )
    options: list[str] | None = Field(
        default=None,
        description="List of 4 distinct choices for multiple_choice; None for essay",
    )
    correct_answer: str = Field(
        default="",
        description="Correct answer choice for multiple_choice, or benchmark model answer for essay",
    )
    explanation: str | None = Field(
        default=None,
        description="Detailed pedagogical explanation and reasoning",
    )
    difficulty: str = Field(
        default="medium",
        description="Difficulty level: 'easy', 'medium', or 'hard'",
    )


class GeneratedQuestionSet(BaseModel):
    """Structured question set output returned by GeminiAdapter."""

    bank_name: str = Field(
        default="Generated Question Bank",
        description="Descriptive title for the question bank based on topic",
    )
    description: str = Field(
        default="AI-generated practice questions",
        description="Concise academic overview of the questions",
    )
    questions: list[GeneratedQuestionItem] = Field(
        default_factory=list,
        description="List of generated questions adhering to requirements",
    )


# ---------------------------------------------------------------------------
# Domain Data Transfer Objects (DTOs)
# ---------------------------------------------------------------------------


class QuestionDTO(BaseModel):
    """Data Transfer Object representing a Question entity."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    question_bank_id: uuid.UUID
    question_type: str
    content: str
    options: list[Any] | None = None
    correct_answer: str | None = None
    explanation: str | None = None
    difficulty: str = "medium"
    created_at: datetime
    updated_at: datetime

    @classmethod
    def from_orm(cls, q: Question) -> QuestionDTO:
        """Create QuestionDTO from SQLAlchemy Question model."""
        return cls(
            id=q.id,
            question_bank_id=q.question_bank_id,
            question_type=q.question_type,
            content=q.content,
            options=q.options,
            correct_answer=q.correct_answer,
            explanation=q.explanation,
            difficulty=q.difficulty,
            created_at=q.created_at,
            updated_at=q.updated_at,
        )


class QuestionBankDTO(BaseModel):
    """Data Transfer Object representing a QuestionBank entity with its questions."""

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    user_id: uuid.UUID
    course_id: uuid.UUID | None = None
    document_id: uuid.UUID | None = None
    name: str
    description: str | None = None
    questions: list[QuestionDTO] = Field(default_factory=list)
    created_at: datetime
    updated_at: datetime

    @classmethod
    def from_orm(cls, bank: QuestionBank) -> QuestionBankDTO:
        """Create QuestionBankDTO from SQLAlchemy QuestionBank model."""
        return cls(
            id=bank.id,
            user_id=bank.user_id,
            course_id=bank.course_id,
            document_id=bank.document_id,
            name=bank.name,
            description=bank.description,
            questions=[QuestionDTO.from_orm(q) for q in (bank.questions or [])],
            created_at=bank.created_at,
            updated_at=bank.updated_at,
        )


