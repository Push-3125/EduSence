class QuestionGenerationService:
    """Service orchestrating AI question bank generation and question management."""

    def __init__(
        self,
        question_repo: QuestionRepository,
        document_repo: DocumentRepository,
        chunk_repo: DocumentChunkRepository,
        gemini_adapter: GeminiAdapter,
        usage_logger: AIUsageLogger,
        quota_service: AIQuotaService,
        sanitizer: PromptSanitizer,
    ) -> None:
        self.question_repo = question_repo
        self.document_repo = document_repo
        self.chunk_repo = chunk_repo
        self.gemini_adapter = gemini_adapter
        self.usage_logger = usage_logger
        self.quota_service = quota_service
        self.sanitizer = sanitizer

    async def generate_questions_from_document(
        self,
        user_id: uuid.UUID,
        document_id: uuid.UUID,
        num_questions: int = 5,
        question_type: str = "multiple_choice",
        difficulty: str = "medium",
        plan_code: str = "free",
    ) -> QuestionBankDTO:
        """Generate a question bank from a document using Google Gemini structured output.

        Args:
            user_id: Student user UUID (tenant isolation).
            document_id: Target document UUID.
            num_questions: Number of questions to generate (1 to 20).
            question_type: 'multiple_choice', 'essay', or 'mixed'.
            difficulty: 'easy', 'medium', or 'hard'.
            plan_code: User subscription tier ('free' or 'pro').

        Returns:
            QuestionBankDTO with created questions.

        Raises:
            DocumentNotFoundError: If document not found or access denied.
            InvalidQuestionConfigError: If parameters are invalid.
            EmptyDocumentError: If document has no text chunks.
            QuotaExceededError: If daily AI quota is exceeded.
            QuotaServiceUnavailableError: If Redis quota counter is unavailable.
        """
        # 1. Validate parameters
        if num_questions < 1 or num_questions > 20:
            raise InvalidQuestionConfigError(
                f"num_questions must be between 1 and 20. Provided: {num_questions}"
            )

        clean_type = question_type.strip().lower()
        if clean_type not in {"multiple_choice", "essay", "mixed"}:
            raise InvalidQuestionConfigError(
                f"Invalid question_type '{question_type}'. Must be one of: 'multiple_choice', 'essay', 'mixed'."
            )

        clean_diff = difficulty.strip().lower()
        if clean_diff not in {"easy", "medium", "hard"}:
            raise InvalidQuestionConfigError(
                f"Invalid difficulty '{difficulty}'. Must be one of: 'easy', 'medium', 'hard'."
            )

        # 2. Strict document ownership verification (Invariant 6)
        doc = await self.document_repo.get_by_id_and_user(document_id, user_id)
        if not doc:
            raise DocumentNotFoundError(
                f"Document {document_id} not found or access denied for user {user_id}."
            )

        # 3. Collect document chunks
        chunks = await self.chunk_repo.get_chunks_by_document(document_id)
        valid_chunks = [c.content for c in chunks if c.content and c.content.strip()]
        if not valid_chunks:
            raise EmptyDocumentError(
                f"Document {document_id} has no text content available for question generation."
            )

        # 4. Build isolated prompt with boundary fences (Invariant 13)
        system_base = (
            f"You are an expert university professor and examination designer for EduSense. "
            f"Your task is to generate high-quality academic questions based strictly on the provided study material. "
            f"Generate exactly {num_questions} questions with difficulty level '{clean_diff}'. "
            f"Question format requirement: {clean_type}. "
            f"- If 'multiple_choice': each question must contain exactly 4 distinct answer options in the 'options' list, "
            f"  and 'correct_answer' must match one of the options. Provide a thorough pedagogical explanation. "
            f"- If 'essay': 'options' must be null/empty, and 'correct_answer' must provide a comprehensive model benchmark solution and rubric guidelines. "
            f"- If 'mixed': provide a balanced combination of multiple_choice and essay questions. "
            f"Ensure rigorous conceptual understanding, test higher-order thinking (Bloom's taxonomy), and avoid trivial recall."
        )
        user_query = (
            f"Generate {num_questions} academic questions (type: {clean_type}, difficulty: {clean_diff}) "
            f"from this document."
        )
        isolated_prompt = self.sanitizer.build_isolated_prompt(
            system_base=system_base,
            user_query=user_query,
            retrieved_contexts=valid_chunks,
        )

        # 5. Atomic quota reservation before LLM call (Invariant 7 & Invariant 4)
        start_time = time.monotonic()
        async with self.quota_service.reserve(user_id=user_id, plan_code=plan_code):
            generated_set: GeneratedQuestionSet = await self.gemini_adapter.agenerate_structured(
                prompt=isolated_prompt.user_content,
                response_schema=GeneratedQuestionSet,
                system_instruction=isolated_prompt.system_instruction,
            )
        latency_ms = int((time.monotonic() - start_time) * 1000)

        # 6. Normalize & Persist to Database
        bank_name = (
            generated_set.bank_name
            if generated_set.bank_name and generated_set.bank_name.strip()
            else f"Question Bank - {doc.title}"
        ).strip()[:255]
        bank_desc = (
            generated_set.description
            if generated_set.description and generated_set.description.strip()
            else f"Generated {clean_type} questions for {doc.title}"
        ).strip()

        bank = await self.question_repo.create_bank(
            user_id=user_id,
            name=bank_name,
            description=bank_desc,
            course_id=doc.course_id,
            document_id=doc.id,
        )

        # Prepare question items strictly conforming to DB constraints
        questions_data: list[dict[str, Any]] = []
        raw_items = generated_set.questions or []

        # If LLM returned empty list, create at least 1 fallback item
        if not raw_items:
            raw_items = [
                GeneratedQuestionItem(
                    question_type="multiple_choice" if clean_type != "essay" else "essay",
                    content=f"Key concept question from {doc.title}",
                    options=["Option A", "Option B", "Option C", "Option D"]
                    if clean_type != "essay"
                    else None,
                    correct_answer="Option A" if clean_type != "essay" else "Comprehensive analysis.",
                    explanation="Based on provided document material.",
                    difficulty=clean_diff,
                )
            ]

        for idx, item in enumerate(raw_items[:num_questions]):
            # Resolve question type
            if clean_type in ("multiple_choice", "essay"):
                q_type = clean_type
            else:
                # Mixed: respect item type or alternate
                if item.question_type in ("multiple_choice", "essay"):
                    q_type = item.question_type
                else:
                    q_type = "multiple_choice" if idx % 2 == 0 else "essay"

            # Resolve difficulty
            q_diff = (
                item.difficulty.strip().lower()
                if item.difficulty and item.difficulty.strip().lower() in ("easy", "medium", "hard")
                else clean_diff
            )

            # Resolve options and correct answer adhering to ck_questions_options
            if q_type == "multiple_choice":
                if item.options and isinstance(item.options, list) and len(item.options) >= 2:
                    q_options = [str(opt) for opt in item.options]
                else:
                    q_options = ["Option A", "Option B", "Option C", "Option D"]
                q_correct = (item.correct_answer or q_options[0]).strip()
            else:
                q_options = None
                q_correct = (item.correct_answer or "Model benchmark answer and criteria.").strip()

            q_content = (item.content or f"Question {idx + 1} from {doc.title}").strip()
            q_explanation = item.explanation.strip() if item.explanation else None

            questions_data.append(
                {
                    "question_type": q_type,
                    "content": q_content,
                    "options": q_options,
                    "correct_answer": q_correct,
                    "explanation": q_explanation,
                    "difficulty": q_diff,
                }
            )

        await self.question_repo.add_questions(bank.id, questions_data)

        # 7. Record AI telemetry (Invariant 4 & 7: no prompts logged)
        prompt_tokens = max(1, len(isolated_prompt.user_content.split()))
        completion_tokens = max(1, len(str(generated_set.model_dump()).split()))
        total_tokens = prompt_tokens + completion_tokens

        await self.usage_logger.log_ai_call(
            user_id=user_id,
            feature="questions",
            model_name=self.gemini_adapter.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
            request_status="success",
        )

        # 8. Reload bank with eager questions and return DTO
        reloaded_bank = await self.question_repo.get_bank(user_id=user_id, bank_id=bank.id)
        if reloaded_bank is None:
            raise QuestionBankNotFoundError(f"Failed to reload question bank {bank.id}.")
        return QuestionBankDTO.from_orm(reloaded_bank)

    async def create_bank(
        self,
        user_id: uuid.UUID,
        name: str,
        description: str | None = None,
        course_id: uuid.UUID | None = None,
        document_id: uuid.UUID | None = None,
    ) -> QuestionBankDTO:
        """Create an empty question bank manually.

        Args:
            user_id: Authenticated student UUID.
            name: Bank title.
            description: Optional description.
            course_id: Optional linked course UUID.
            document_id: Optional linked document UUID.

        Returns:
            QuestionBankDTO of the created bank.
        """
        clean_name = name.strip()
        if not clean_name:
            raise InvalidQuestionConfigError("Question bank name cannot be empty.")

        if document_id is not None:
            doc = await self.document_repo.get_by_id_and_user(document_id, user_id)
            if not doc:
                raise DocumentNotFoundError(
                    f"Document {document_id} not found or access denied for user {user_id}."
                )

        bank = await self.question_repo.create_bank(
            user_id=user_id,
            name=clean_name,
            description=description.strip() if description else None,
            course_id=course_id,
            document_id=document_id,
        )
        return QuestionBankDTO.from_orm(bank)

    async def get_bank(
        self,
        user_id: uuid.UUID,
        bank_id: uuid.UUID,
    ) -> QuestionBankDTO:
        """Fetch a question bank with its questions strictly enforcing user ownership.

        Args:
            user_id: Authenticated student UUID.
            bank_id: Target question bank UUID.

        Returns:
            QuestionBankDTO if found.

        Raises:
            QuestionBankNotFoundError: If bank not found or access denied.
        """
        bank = await self.question_repo.get_bank(user_id=user_id, bank_id=bank_id)
        if bank is None:
            raise QuestionBankNotFoundError(
                f"Question bank {bank_id} not found or access denied."
            )
        return QuestionBankDTO.from_orm(bank)

    async def list_banks(
        self,
        user_id: uuid.UUID,
        skip: int = 0,
        limit: int = 50,
        course_id: uuid.UUID | None = None,
    ) -> tuple[list[QuestionBankDTO], int]:
        """List question banks belonging to the user with pagination.

        Args:
            user_id: Authenticated student UUID.
            skip: Pagination offset.
            limit: Maximum items to return.
            course_id: Optional course filter.

        Returns:
            Tuple of (list of QuestionBankDTO, total count).
        """
        banks, total = await self.question_repo.list_banks(
            user_id=user_id, skip=skip, limit=limit, course_id=course_id
        )
        return [QuestionBankDTO.from_orm(b) for b in banks], total

    async def delete_bank(
        self,
        user_id: uuid.UUID,
        bank_id: uuid.UUID,
    ) -> bool:
        """Delete a question bank enforcing ownership.

        Args:
            user_id: Authenticated student UUID.
            bank_id: Target question bank UUID.

        Returns:
            True if deleted successfully.

        Raises:
            QuestionBankNotFoundError: If bank not found or access denied.
        """
        deleted = await self.question_repo.delete_bank(user_id=user_id, bank_id=bank_id)
        if not deleted:
            raise QuestionBankNotFoundError(
                f"Question bank {bank_id} not found or access denied."
            )
        return True

    async def add_question(
        self,
        user_id: uuid.UUID,
        bank_id: uuid.UUID,
        question_type: str,
        content: str,
        options: list[str] | None = None,
        correct_answer: str | None = None,
        explanation: str | None = None,
        difficulty: str = "medium",
    ) -> QuestionDTO:
        """Manually add a single question to an existing bank.

        Args:
            user_id: Authenticated student UUID.
            bank_id: Target question bank UUID.
            question_type: 'multiple_choice' or 'essay'.
            content: Question statement.
            options: List of choices for multiple_choice.
            correct_answer: Correct answer text.
            explanation: Optional reasoning explanation.
            difficulty: 'easy', 'medium', or 'hard'.

        Returns:
            Created QuestionDTO.

        Raises:
            QuestionBankNotFoundError: If bank not found or access denied.
            InvalidQuestionConfigError: If question parameters are invalid.
        """
        bank = await self.question_repo.get_bank(user_id=user_id, bank_id=bank_id)
        if bank is None:
            raise QuestionBankNotFoundError(
                f"Question bank {bank_id} not found or access denied."
            )

        clean_type = question_type.strip().lower()
        if clean_type not in ("multiple_choice", "essay"):
            raise InvalidQuestionConfigError(
                f"Invalid question_type '{question_type}'. Must be 'multiple_choice' or 'essay'."
            )

        clean_diff = difficulty.strip().lower()
        if clean_diff not in ("easy", "medium", "hard"):
            raise InvalidQuestionConfigError(
                f"Invalid difficulty '{difficulty}'. Must be 'easy', 'medium', or 'hard'."
            )

        clean_content = content.strip()
        if not clean_content:
            raise InvalidQuestionConfigError("Question content cannot be empty.")

        resolved_options: list[str] | None
        resolved_correct: str | None

        if clean_type == "multiple_choice":
            if not options or not isinstance(options, list) or len(options) < 2:
                raise InvalidQuestionConfigError(
                    "Multiple choice questions require at least 2 options in an array."
                )
            mc_options = [str(opt) for opt in options]
            resolved_options = mc_options
            resolved_correct = (correct_answer or mc_options[0]).strip()
        else:
            resolved_options = None
            resolved_correct = correct_answer.strip() if correct_answer else None

        questions = await self.question_repo.add_questions(
            bank_id=bank_id,
            questions_data=[
                {
                    "question_type": clean_type,
                    "content": clean_content,
                    "options": resolved_options,
                    "correct_answer": resolved_correct,
                    "explanation": explanation.strip() if explanation else None,
                    "difficulty": clean_diff,
                }
            ],
        )
        return QuestionDTO.from_orm(questions[0])

    async def delete_question(
        self,
        user_id: uuid.UUID,
        bank_id: uuid.UUID,
        question_id: uuid.UUID,
    ) -> bool:
        """Delete a single question from a bank, verifying ownership.

        Args:
            user_id: Authenticated student UUID.
            bank_id: Question bank UUID.
            question_id: Target question UUID.

        Returns:
            True if deleted.

        Raises:
            QuestionBankNotFoundError: If bank not found or access denied.
            QuestionNotFoundError: If question not found in bank or access denied.
        """
        bank = await self.question_repo.get_bank(user_id=user_id, bank_id=bank_id)
        if bank is None:
            raise QuestionBankNotFoundError(
                f"Question bank {bank_id} not found or access denied."
            )

        deleted = await self.question_repo.delete_question(
            user_id=user_id, bank_id=bank_id, question_id=question_id
        )
        if not deleted:
            raise QuestionNotFoundError(
                f"Question {question_id} not found in bank {bank_id} or access denied."
            )
        return True


