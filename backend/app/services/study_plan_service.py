"""AI Study & Revision Plan Generation Service (TASK-M5-05 / US 2.16).

Adheres strictly to EduSense Invariants:
- Invariant 2 (Layering): Router -> Service -> Repository. No repositories imported in routers.
- Invariant 4 (Central LLM): Gemini called only via GeminiAdapter.agenerate_structured.
- Invariant 6 (Tenant Isolation): All plans and items strictly filtered by user_id.
- Invariant 7 (Quota & Telemetry): Atomic quota reservation via quota_service.reserve;
  telemetry logged via usage_logger.log_ai_call without plain prompt persistence.
- Invariant 13 (Untrusted Context Fencing): Prompts fenced via PromptSanitizer.
- Database Constraints: Respects all check constraints on study_plans & study_plan_items.
"""

