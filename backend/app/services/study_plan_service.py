# ---------------------------------------------------------------------------
# Domain Exceptions
# ---------------------------------------------------------------------------


class StudyPlanServiceError(Exception):
    """Base exception for study plan service domain errors."""


class StudyPlanNotFoundError(StudyPlanServiceError):
    """Raised when a study plan or item is not found or not owned by user."""


class InvalidPlanDateError(StudyPlanServiceError):
    """Raised when plan end_date < start_date or date range is invalid."""


# ---------------------------------------------------------------------------
# Pydantic Schemas for Structured LLM Generation
# ---------------------------------------------------------------------------


class GeneratedPlanItem(BaseModel):
    """A single scheduled study session generated by Gemini."""

    title: str = Field(..., description="Actionable title of the study or revision session")
    description: str | None = Field(
        default=None, description="Detailed topics, chapters, and tasks to review"
    )
    day_offset: int = Field(
        ..., ge=0, description="Day offset relative to start_date (0 = start_date)"
    )
    start_time: str = Field(
        default="09:00",
        description="Scheduled start time of the session in 24-hour format HH:MM (e.g. '09:00', '14:30')",
    )
    duration_minutes: int = Field(
        default=60, ge=15, le=480, description="Duration of study session in minutes"
    )
    course_name: str | None = Field(
        default=None, description="Name or code of the related course if applicable"
    )


class GeneratedPlanOutput(BaseModel):
    """Complete structured study plan generated by Gemini."""

    plan_name: str = Field(..., description="Descriptive title of the study plan")
    rationale: str = Field(
        ...,
        description="Pedagogical explanation of how the plan balances workload, class commitments, and exam deadlines",
    )
    items: list[GeneratedPlanItem] = Field(
        default_factory=list, description="Array of scheduled study sessions"
    )


# ---------------------------------------------------------------------------
# Data Transfer Objects (DTOs)
# ---------------------------------------------------------------------------


class StudyPlanItemDTO(BaseModel):
    """Decoupled Data Transfer Object for a study plan item."""

    id: uuid.UUID
    study_plan_id: uuid.UUID
    course_id: uuid.UUID | None = None
    title: str
    description: str | None = None
    scheduled_start: datetime
    scheduled_end: datetime | None = None
    status: str = "pending"
    completed_at: datetime | None = None
    accepted_at: datetime | None = None
    display_order: int = 0
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}

    @classmethod
    def from_orm(cls, obj: Any) -> StudyPlanItemDTO:
        """Create DTO from ORM model or mapping."""
        return cls.model_validate(obj)


class StudyPlanDTO(BaseModel):
    """Decoupled Data Transfer Object for a full study plan."""

    id: uuid.UUID
    user_id: uuid.UUID
    name: str
    description: str | None = None
    start_date: date
    end_date: date
    status: str = "draft"
    generated_by_ai: bool = False
    created_at: datetime
    updated_at: datetime
    items: list[StudyPlanItemDTO] = Field(default_factory=list)

    model_config = {"from_attributes": True}

    @classmethod
    def from_orm(cls, obj: Any) -> StudyPlanDTO:
        """Create DTO from ORM model or mapping."""
        return cls.model_validate(obj)


# ---------------------------------------------------------------------------
# Service Implementation
# ---------------------------------------------------------------------------


class StudyPlanService:
    """Service orchestrating AI study plan generation and CRUD operations."""

    def __init__(
        self,
        study_plan_repo: StudyPlanRepository,
        calendar_service: CalendarService,
        gemini_adapter: GeminiAdapter,
        sanitizer: PromptSanitizer,
        quota_service: AIQuotaService,
        usage_logger: AIUsageLogger,
    ) -> None:
        self.study_plan_repo = study_plan_repo
        self.calendar_service = calendar_service
        self.gemini_adapter = gemini_adapter
        self.sanitizer = sanitizer
        self.quota_service = quota_service
        self.usage_logger = usage_logger

    async def generate_ai_study_plan(
        self,
        user_id: uuid.UUID,
        name: str | None,
        start_date: date,
        end_date: date,
        target_goals: str | None = None,
        plan_code: str = "free",
    ) -> StudyPlanDTO:
        """Generate an AI-driven study and revision plan adhering to US 2.16."""
        # 1. Domain Validation
        if end_date < start_date:
            raise InvalidPlanDateError(
                f"end_date ({end_date}) cannot be earlier than start_date ({start_date})."
            )

        total_days = (end_date - start_date).days

        # 2. Query Student Academic Commitments for Real Context
        from_dt = datetime.combine(start_date, time.min).replace(tzinfo=UTC)
        to_dt = datetime.combine(end_date, time.max).replace(tzinfo=UTC)

        academic_events_summary: list[str] = []
        course_name_map: dict[str, uuid.UUID] = {}

        try:
            calendar_data = await self.calendar_service.get_aggregated_calendar(
                user_id=user_id,
                from_date=from_dt,
                to_date=to_dt,
            )
            for event in calendar_data.events:
                course_name_map[event.course_name.strip().lower()] = event.course_id
                if event.course_code:
                    course_name_map[event.course_code.strip().lower()] = event.course_id

                academic_events_summary.append(
                    f"[{event.event_type.upper()}] Course: {event.course_name} ({event.course_code or 'N/A'}) | "
                    f"Title: {event.title} | Start: {event.start_time.isoformat()} | "
                    f"End: {event.end_time.isoformat() if event.end_time else 'N/A'} | "
                    f"Priority: {event.priority or 'medium'}"
                )
        except (CalendarServiceError, OSError, ValueError, RuntimeError) as exc:
            logger.warning("Failed to query academic calendar for user %s: %s", user_id, exc)

        # Also retrieve student courses for course name matching if possible
        try:
            if hasattr(self.calendar_service, "course_repo"):
                courses, _ = await self.calendar_service.course_repo.list_by_user(user_id=user_id)
                for c in courses:
                    course_name_map[c.name.strip().lower()] = c.id
                    if c.course_code:
                        course_name_map[c.course_code.strip().lower()] = c.id
        except (AttributeError, OSError, ValueError, RuntimeError) as exc:
            logger.debug("Failed to list student courses for study plan: %s", exc)

        # 3. Prompt Isolation & Fencing (Invariant 13)
        clean_name = self.sanitizer.sanitize_user_input(name or "", strict=False)
        clean_goals = self.sanitizer.sanitize_user_input(target_goals or "", strict=False)

        system_instruction = (
            "You are an expert AI academic advisor and revision planner for university students. "
            "Your objective is to generate a realistic, pedagogically sound, and balanced study and revision plan. "
            f"The schedule runs from {start_date.isoformat()} to {end_date.isoformat()} ({total_days + 1} days total). "
            "Analyze the student's scheduled academic commitments (classes, assignment deadlines, and exams). "
            "Prioritize studying for upcoming exams and completing assignments before deadlines. "
            "Never schedule revision sessions that conflict with scheduled class sessions.\n"
            "Requirements for generated items:\n"
            f"1. 'day_offset' must be an integer between 0 and {total_days}.\n"
            "2. 'start_time' must be in 24-hour format 'HH:MM' (e.g. '09:00', '14:30', '19:00').\n"
            "3. 'duration_minutes' must be between 15 and 240 minutes (standard: 45-90 minutes).\n"
            "4. 'course_name' should match relevant courses from the provided academic context when applicable.\n"
            "5. Provide an insightful 'rationale' explaining how the study plan balances student workload."
        )

        user_content = (
            f"Requested Plan Name: {clean_name or 'Personal Study & Revision Plan'}\n"
            f"Target Study Goals: {clean_goals or 'Comprehensive exam revision and coursework completion'}\n"
            f"Date Range: {start_date.isoformat()} to {end_date.isoformat()} ({total_days + 1} days total)."
        )

        retrieved_contexts = (
            academic_events_summary
            if academic_events_summary
            else ["No scheduled classes, assignments, or exams recorded in this timeframe."]
        )

        isolated_prompt = self.sanitizer.build_isolated_prompt(
            system_base=system_instruction,
            user_query=user_content,
            retrieved_contexts=retrieved_contexts,
            strict_check=False,
        )

        # 4. Atomic Quota Reservation & Gemini Generation (Invariant 4 & 7)
        async with self.quota_service.reserve(user_id=user_id, plan_code=plan_code):
            start_perf = py_time.perf_counter()
            structured_plan: GeneratedPlanOutput = (
                await self.gemini_adapter.agenerate_structured(
                    prompt=isolated_prompt.user_content,
                    response_schema=GeneratedPlanOutput,
                    system_instruction=isolated_prompt.system_instruction,
                    temperature=0.2,
                )
            )
            latency_ms = int((py_time.perf_counter() - start_perf) * 1000)

        # 5. Persist Study Plan Header
        resolved_name = (
            name
            or structured_plan.plan_name
            or f"Study Plan {start_date.isoformat()} to {end_date.isoformat()}"
        ).strip()
        description = structured_plan.rationale.strip() if structured_plan.rationale else None
        if target_goals and target_goals.strip():
            description = (
                f"{description}\n\nGoals: {target_goals.strip()}"
                if description
                else f"Goals: {target_goals.strip()}"
            )

        plan = await self.study_plan_repo.create_plan(
            user_id=user_id,
            name=resolved_name,
            start_date=start_date,
            end_date=end_date,
            description=description,
            generated_by_ai=True,
            status="draft",
        )

        # 6. Map and Persist Generated Items
        items_data: list[dict[str, Any]] = []
        for idx, item in enumerate(structured_plan.items):
            # Clamp day_offset to [0, total_days]
            offset = max(0, min(item.day_offset, total_days))
            item_date = start_date + timedelta(days=offset)

            # Parse start_time HH:MM
            hour, minute = 9, 0
            if item.start_time and ":" in item.start_time:
                parts = item.start_time.strip().split(":")
                try:
                    h = int(parts[0])
                    m = int(parts[1])
                    if 0 <= h < 24 and 0 <= m < 60:
                        hour, minute = h, m
                except (ValueError, IndexError):
                    hour, minute = 9, 0

            sched_start = datetime.combine(item_date, time(hour, minute)).replace(
                tzinfo=UTC
            )
            duration_mins = max(15, min(item.duration_minutes or 60, 480))
            sched_end = sched_start + timedelta(minutes=duration_mins)

            # Map course_id if course_name is recognized
            matched_course_id: uuid.UUID | None = None
            if item.course_name and item.course_name.strip().lower() in course_name_map:
                matched_course_id = course_name_map[item.course_name.strip().lower()]

            items_data.append(
                {
                    "course_id": matched_course_id,
                    "title": item.title.strip() if item.title else f"Study Session {idx + 1}",
                    "description": item.description.strip() if item.description else None,
                    "scheduled_start": sched_start,
                    "scheduled_end": sched_end,
                    "status": "pending",
                    "accepted_at": None,
                    "completed_at": None,
                    "display_order": idx,
                }
            )

        if items_data:
            await self.study_plan_repo.add_items(plan_id=plan.id, items_data=items_data)

        # 7. Record Telemetry (Invariant 4 & 7)
        prompt_tokens = max(1, len(isolated_prompt.user_content.split()))
        completion_tokens = max(1, len(str(structured_plan.model_dump()).split()))
        total_tokens = prompt_tokens + completion_tokens

        await self.usage_logger.log_ai_call(
            user_id=user_id,
            feature="study_plan",
            model_name=self.gemini_adapter.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            latency_ms=latency_ms,
            request_status="success",
        )

        # 8. Reload Plan with Eager Items
        reloaded = await self.study_plan_repo.get_plan(user_id=user_id, plan_id=plan.id)
        if reloaded is None:
            raise StudyPlanNotFoundError("Failed to reload generated study plan.")
        return StudyPlanDTO.from_orm(reloaded)

    async def create_plan(
        self,
        user_id: uuid.UUID,
        name: str,
        start_date: date,
        end_date: date,
        description: str | None = None,
    ) -> StudyPlanDTO:
        """Create a study plan manually without AI."""
        if end_date < start_date:
            raise InvalidPlanDateError(
                f"end_date ({end_date}) cannot be earlier than start_date ({start_date})."
            )

        plan = await self.study_plan_repo.create_plan(
            user_id=user_id,
            name=name,
            start_date=start_date,
            end_date=end_date,
            description=description,
            generated_by_ai=False,
            status="draft",
        )

        reloaded = await self.study_plan_repo.get_plan(user_id=user_id, plan_id=plan.id)
        if reloaded is None:
            raise StudyPlanNotFoundError("Failed to load created study plan.")
        return StudyPlanDTO.from_orm(reloaded)

    async def get_plan(self, user_id: uuid.UUID, plan_id: uuid.UUID) -> StudyPlanDTO:
        """Retrieve a specific study plan and its items, enforcing tenant isolation."""
        plan = await self.study_plan_repo.get_plan(user_id=user_id, plan_id=plan_id)
        if plan is None:
            raise StudyPlanNotFoundError(f"Study plan {plan_id} not found.")
        return StudyPlanDTO.from_orm(plan)

    async def list_plans(
        self,
        user_id: uuid.UUID,
        skip: int = 0,
        limit: int = 50,
        status: str | None = None,
    ) -> tuple[list[StudyPlanDTO], int]:
        """List study plans for user with pagination and total count."""
        plans, total = await self.study_plan_repo.list_plans(
            user_id=user_id, skip=skip, limit=limit, status=status
        )
        return [StudyPlanDTO.from_orm(p) for p in plans], total

    async def delete_plan(self, user_id: uuid.UUID, plan_id: uuid.UUID) -> bool:
        """Delete a study plan, enforcing tenant isolation."""
        deleted = await self.study_plan_repo.delete_plan(user_id=user_id, plan_id=plan_id)
        if not deleted:
            raise StudyPlanNotFoundError(f"Study plan {plan_id} not found.")
        return True

    async def update_item_status(
        self,
        user_id: uuid.UUID,
        plan_id: uuid.UUID,
        item_id: uuid.UUID,
        status: str,
    ) -> StudyPlanItemDTO:
        """Update a study plan item's status, enforcing tenant isolation and check constraints."""
        valid_statuses = {"pending", "accepted", "in_progress", "completed", "dismissed"}
        clean_status = status.strip().lower()
        if clean_status not in valid_statuses:
            raise ValueError(
                f"Invalid status '{status}'. Must be one of: {', '.join(sorted(valid_statuses))}"
            )

        item = await self.study_plan_repo.update_item_status(
            user_id=user_id,
            plan_id=plan_id,
            item_id=item_id,
            status=clean_status,
        )
        if item is None:
            raise StudyPlanNotFoundError(f"Study plan item {item_id} not found.")
        return StudyPlanItemDTO.from_orm(item)


def get_study_plan_service(
    study_plan_repo: Annotated[StudyPlanRepository, Depends(get_study_plan_repo)],
    calendar_service: Annotated[CalendarService, Depends(get_calendar_service)],
    gemini_adapter: Annotated[GeminiAdapter, Depends(get_gemini_adapter)],
    sanitizer: Annotated[PromptSanitizer, Depends(get_prompt_sanitizer)],
    quota_service: Annotated[AIQuotaService, Depends(get_quota_service)],
    usage_logger: Annotated[AIUsageLogger, Depends(get_ai_usage_logger)],
) -> StudyPlanService:
    """FastAPI dependency provider for StudyPlanService."""
    return StudyPlanService(
        study_plan_repo=study_plan_repo,
        calendar_service=calendar_service,
        gemini_adapter=gemini_adapter,
        sanitizer=sanitizer,
        quota_service=quota_service,
        usage_logger=usage_logger,
    )


