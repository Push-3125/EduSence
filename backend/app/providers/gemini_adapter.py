"""Google Gemini Central LLM Adapter for EduSense (TASK-M4-01).

Adheres strictly to EduSense Invariant 4:
"Exactly one place calls Google Gemini: the shared LLM & Embedding Adapter (app/providers/).
Routers and worker tasks never call the Gemini SDK directly."

Provides text generation, structured JSON extraction via Pydantic schemas, and multi-turn
chat with automatic circuit breaker protection and exponential backoff retries.
"""

from __future__ import annotations

import asyncio
import inspect
import logging
import time
from collections.abc import Awaitable, Callable
from functools import lru_cache
from typing import Any, Literal, TypeVar

from google import genai
from google.genai import errors, types
from pydantic import BaseModel, Field
from pydantic_core import PydanticUndefined

from app.core.config import settings
from app.providers.circuit_breaker import (
    CircuitBreaker,
    CircuitBreakerOpenError,
)

logger = logging.getLogger("edusense.providers.gemini")

ModelT = TypeVar("ModelT", bound=BaseModel)
T = TypeVar("T")


# ---------------------------------------------------------------------------
# Domain Models & Data Structures
# ---------------------------------------------------------------------------


class ChatMessage(BaseModel):
    """Chat message structure for multi-turn conversations."""

    role: Literal["user", "model", "system"] | str = Field(
        ...,
        description="Role of the message sender ('user', 'model', or 'system')",
    )
    content: str = Field(..., description="Message text content")


class GeminiResponse(BaseModel):
    """Standardized response container for Gemini text generation."""

    text: str = Field(..., description="Generated text response from the model")
    model: str = Field(..., description="Model identifier used for generation")
    prompt_tokens: int = Field(default=0, description="Tokens in the input prompt")
    completion_tokens: int = Field(default=0, description="Tokens generated by the model")
    total_tokens: int = Field(default=0, description="Total tokens consumed")
    finish_reason: str | None = Field(
        default=None, description="Reason model stopped generating (e.g. STOP, MAX_TOKENS)"
    )


# ---------------------------------------------------------------------------
# Domain Exceptions
# ---------------------------------------------------------------------------


class GeminiAdapterError(Exception):
    """Base exception for all Gemini adapter errors."""


class GeminiRateLimitError(GeminiAdapterError):
    """Raised when Gemini API rate limit or quota is exceeded (HTTP 429)."""


class GeminiTimeoutError(GeminiAdapterError):
    """Raised when a request to Gemini API times out."""


class GeminiConfigurationError(GeminiAdapterError):
    """Raised when Gemini adapter is misconfigured."""


class GeminiCircuitOpenError(GeminiAdapterError):
    """Raised when a request is rejected because the circuit breaker is OPEN."""

    def __init__(self, message: str, retry_after: float | None = None) -> None:
        super().__init__(message)
        self.retry_after = retry_after


# ---------------------------------------------------------------------------
# Gemini Adapter Implementation
# ---------------------------------------------------------------------------


class GeminiAdapter:
    """Centralized adapter for Google Gemini LLM API with circuit breaker and retry."""

    def __init__(
        self,
        api_key: str | None = None,
        model: str | None = None,
        client: Any = None,
        circuit_breaker: CircuitBreaker | None = None,
        test_mode: bool = False,
        max_retries: int = 3,
        initial_retry_delay: float = 0.5,
        max_retry_delay: float = 4.0,
    ) -> None:
        """Initialize the GeminiAdapter.

        Args:
            api_key: Optional Gemini API key override (defaults to settings.gemini_api_key).
            model: Optional model identifier override (defaults to settings.gemini_model).
            client: Optional pre-configured genai.Client or mock double for testing.
            circuit_breaker: Optional CircuitBreaker instance.
            test_mode: If True, operates in mock mode without calling Google API.
            max_retries: Maximum number of retry attempts for transient errors.
            initial_retry_delay: Initial retry backoff delay in seconds.
            max_retry_delay: Maximum retry backoff delay in seconds.
        """
        self.model = model or settings.gemini_model or "gemini-2.5-flash"
        if not self.model or not self.model.strip():
            raise GeminiConfigurationError("Gemini model name cannot be empty.")

        self.test_mode = test_mode
        self.max_retries = max(0, max_retries)
        self.initial_retry_delay = max(0.0, initial_retry_delay)
        self.max_retry_delay = max(self.initial_retry_delay, max_retry_delay)

        self._circuit_breaker = circuit_breaker or CircuitBreaker(
            failure_threshold=5,
            recovery_timeout=30.0,
            half_open_success_threshold=2,
        )

        resolved_api_key = api_key or settings.gemini_api_key

        if client is not None:
            self._client: Any = client
        elif resolved_api_key and not self.test_mode:
            self._client = genai.Client(api_key=resolved_api_key)
        else:
            self._client = None
            self.test_mode = True
            logger.info("GeminiAdapter initialized in mock/test mode.")

    @property
    def circuit_breaker(self) -> CircuitBreaker:
        """Access the underlying CircuitBreaker instance."""
        return self._circuit_breaker

    # -----------------------------------------------------------------------
    # Exception Mapping & Retry Helpers
    # -----------------------------------------------------------------------

    def _map_exception(self, exc: Exception) -> Exception:
        """Map external SDK or system exceptions to GeminiAdapter domain exceptions."""
        if isinstance(exc, GeminiAdapterError):
            return exc

        if isinstance(exc, CircuitBreakerOpenError):
            return GeminiCircuitOpenError(str(exc), retry_after=exc.retry_after)

        if isinstance(exc, (TimeoutError, asyncio.TimeoutError)):
            return GeminiTimeoutError(f"Gemini request timed out: {exc}")

        if isinstance(exc, errors.APIError):
            code = getattr(exc, "code", None)
            message = getattr(exc, "message", str(exc))
            if code == 429 or "RESOURCE_EXHAUSTED" in str(exc) or "429" in str(exc):
                return GeminiRateLimitError(f"Gemini rate limit exceeded (HTTP 429): {message}")
            if code in (500, 502, 503, 504) or "503" in str(exc) or "UNAVAILABLE" in str(exc):
                return GeminiAdapterError(f"Gemini server error (HTTP {code}): {message}")
            return GeminiAdapterError(f"Gemini API error (HTTP {code}): {message}")

        msg = str(exc).lower()
        if any(k in msg for k in ("timed out", "timeout")):
            return GeminiTimeoutError(f"Gemini request timed out: {exc}")
        if any(k in msg for k in ("rate limit", "quota", "resource_exhausted", "429")):
            return GeminiRateLimitError(f"Gemini rate limit exceeded: {exc}")

        return GeminiAdapterError(f"Gemini call failed: {exc}")

    def _is_transient_error(self, exc: Exception) -> bool:
        """Determine if an exception represents a transient failure eligible for retry."""
        if isinstance(exc, (GeminiRateLimitError, GeminiTimeoutError)):
            return True
        if isinstance(exc, errors.APIError):
            code = getattr(exc, "code", None)
            if code in (429, 502, 503, 504):
                return True
        msg = str(exc).lower()
        return any(
            k in msg
            for k in (
                "429",
                "502",
                "503",
                "504",
                "resource_exhausted",
                "unavailable",
                "timed out",
                "timeout",
            )
        )

    def _execute_with_retry_sync(self, operation: Callable[[], T]) -> T:
        """Execute a synchronous operation with circuit breaker and exponential backoff."""
        last_exc: Exception | None = None
        for attempt in range(self.max_retries + 1):
            try:
                return self._circuit_breaker.call(operation)
            except CircuitBreakerOpenError as exc:
                raise GeminiCircuitOpenError(str(exc), retry_after=exc.retry_after) from exc
            except Exception as exc:
                mapped_exc = self._map_exception(exc)
                last_exc = mapped_exc
                if attempt < self.max_retries and self._is_transient_error(mapped_exc):
                    delay = min(self.initial_retry_delay * (2**attempt), self.max_retry_delay)
                    logger.warning(
                        "Gemini transient failure on attempt %d/%d (%s). Retrying in %.2fs...",
                        attempt + 1,
                        self.max_retries,
                        mapped_exc,
                        delay,
                    )
                    time.sleep(delay)
                    continue
                raise mapped_exc from exc

        if last_exc:
            raise last_exc
        raise GeminiAdapterError("Operation failed with unknown error.")

    async def _execute_with_retry_async(self, coro_func: Callable[[], Awaitable[T]]) -> T:
        """Execute an asynchronous operation with circuit breaker and exponential backoff."""
        last_exc: Exception | None = None
        for attempt in range(self.max_retries + 1):
            try:
                return await self._circuit_breaker.acall(coro_func)
            except CircuitBreakerOpenError as exc:
                raise GeminiCircuitOpenError(str(exc), retry_after=exc.retry_after) from exc
            except Exception as exc:
                mapped_exc = self._map_exception(exc)
                last_exc = mapped_exc
                if attempt < self.max_retries and self._is_transient_error(mapped_exc):
                    delay = min(self.initial_retry_delay * (2**attempt), self.max_retry_delay)
                    logger.warning(
                        "Gemini async transient failure on attempt %d/%d (%s). Retrying in %.2fs...",
                        attempt + 1,
                        self.max_retries,
                        mapped_exc,
                        delay,
                    )
                    await asyncio.sleep(delay)
                    continue
                raise mapped_exc from exc

        if last_exc:
            raise last_exc
        raise GeminiAdapterError("Async operation failed with unknown error.")

    # -----------------------------------------------------------------------
    # Response Parsing & Mock Generators
    # -----------------------------------------------------------------------

    def _extract_response(self, response: Any) -> GeminiResponse:
        """Extract text, tokens, and finish reason from Gemini API response object."""
        text = ""
        if hasattr(response, "text") and response.text is not None:
            text = response.text
        elif hasattr(response, "candidates") and response.candidates:
            c = response.candidates[0]
            if hasattr(c, "content") and hasattr(c.content, "parts") and c.content.parts:
                text = "".join(
                    getattr(p, "text", "") for p in c.content.parts if getattr(p, "text", None)
                )
        elif isinstance(response, dict):
            text = response.get("text", "")

        prompt_tokens = 0
        completion_tokens = 0
        total_tokens = 0

        if hasattr(response, "usage_metadata") and response.usage_metadata is not None:
            u = response.usage_metadata
            prompt_tokens = getattr(u, "prompt_token_count", 0) or 0
            completion_tokens = getattr(u, "candidates_token_count", 0) or 0
            total_tokens = getattr(u, "total_token_count", 0) or (prompt_tokens + completion_tokens)
        elif isinstance(response, dict) and "usage_metadata" in response:
            u = response["usage_metadata"]
            if isinstance(u, dict):
                prompt_tokens = u.get("prompt_token_count", 0) or 0
                completion_tokens = u.get("candidates_token_count", 0) or 0
                total_tokens = u.get("total_token_count", prompt_tokens + completion_tokens) or 0

        finish_reason: str | None = None
        if hasattr(response, "candidates") and response.candidates:
            c = response.candidates[0]
            fr = getattr(c, "finish_reason", None)
            if fr is not None:
                finish_reason = getattr(fr, "name", str(fr))
        elif isinstance(response, dict) and "finish_reason" in response:
            finish_reason = response["finish_reason"]

        return GeminiResponse(
            text=text,
            model=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            finish_reason=finish_reason,
        )

    def _parse_structured_response(self, response: Any, response_schema: type[ModelT]) -> ModelT:
        """Parse structured response using SDK parsed attribute or Pydantic JSON parsing."""
        if hasattr(response, "parsed") and response.parsed is not None:
            if isinstance(response.parsed, response_schema):
                return response.parsed
            if isinstance(response.parsed, dict):
                return response_schema.model_validate(response.parsed)

        text = ""
        if hasattr(response, "text") and response.text is not None:
            text = response.text
        elif hasattr(response, "candidates") and response.candidates:
            c = response.candidates[0]
            if hasattr(c, "content") and hasattr(c.content, "parts") and c.content.parts:
                text = "".join(
                    getattr(p, "text", "") for p in c.content.parts if getattr(p, "text", None)
                )
        elif isinstance(response, dict) and "text" in response:
            text = response["text"]

        if not text or not text.strip():
            raise GeminiAdapterError("Gemini returned empty text for structured response.")

        clean_text = text.strip()
        if clean_text.startswith("```json"):
            clean_text = clean_text[7:]
        elif clean_text.startswith("```"):
            clean_text = clean_text[3:]
        clean_text = clean_text.removesuffix("```")
        clean_text = clean_text.strip()

        try:
            return response_schema.model_validate_json(clean_text)
        except Exception as exc:
            logger.error(
                "Failed to parse structured output with schema %s: %s (Raw text: %s)",
                response_schema.__name__,
                exc,
                clean_text,
            )
            raise GeminiAdapterError(
                f"Failed to validate response against schema {response_schema.__name__}: {exc}"
            ) from exc

    def _mock_text_response(self, prompt: str) -> GeminiResponse:
        """Generate deterministic mock text response for test mode."""
        clean = prompt.strip() or "Empty prompt"
        snippet = clean[:60].replace("\n", " ")
        text = f"[Mock Gemini] Response for: {snippet}"
        prompt_tokens = max(1, len(clean.split()))
        completion_tokens = max(1, len(text.split()))
        total_tokens = prompt_tokens + completion_tokens
        return GeminiResponse(
            text=text,
            model=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            finish_reason="STOP",
        )

    def _mock_chat_response(self, messages: list[ChatMessage]) -> GeminiResponse:
        """Generate deterministic mock chat response for test mode."""
        last_msg = messages[-1].content if messages else "Hello"
        snippet = last_msg[:60].replace("\n", " ")
        text = f"[Mock Gemini Chat] Response to: {snippet}"
        prompt_tokens = sum(max(1, len(m.content.split())) for m in messages) or 1
        completion_tokens = max(1, len(text.split()))
        total_tokens = prompt_tokens + completion_tokens
        return GeminiResponse(
            text=text,
            model=self.model,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            finish_reason="STOP",
        )

    def _mock_structured_response(self, schema: type[ModelT]) -> ModelT:
        """Generate deterministic mock Pydantic model instance for test mode."""
        import types as py_types
        import typing

        def _mock_val(ann: Any, field_name: str) -> Any:
            origin = getattr(ann, "__origin__", None)
            args = getattr(ann, "__args__", ())

            # Handle Optional / Union
            if origin in (typing.Union, py_types.UnionType):
                non_none = [a for a in args if a is not type(None)]
                if non_none:
                    return _mock_val(non_none[0], field_name)
                return None

            if ann is str or ann == "str":
                return f"mock_{field_name}"
            if ann is int or ann == "int":
                return 42
            if ann is float or ann == "float":
                return 1.0
            if ann is bool or ann == "bool":
                return True

            if origin is list or ann is list:
                sub = args[0] if args else str
                return [_mock_val(sub, f"{field_name}_item")]

            if isinstance(ann, type) and issubclass(ann, BaseModel):
                sub_data: dict[str, Any] = {}
                for sub_name, sub_f in ann.model_fields.items():
                    if sub_f.default is not PydanticUndefined and sub_f.default is not None:
                        sub_data[sub_name] = sub_f.default
                    elif sub_f.default_factory is not None:
                        sub_data[sub_name] = sub_f.default_factory()  # type: ignore[call-arg]
                    else:
                        sub_data[sub_name] = _mock_val(sub_f.annotation, sub_name)
                return ann.model_validate(sub_data)

            return f"mock_{field_name}"

        data: dict[str, Any] = {}
        for name, field in schema.model_fields.items():
            if field.default is not PydanticUndefined and field.default is not None:
                data[name] = field.default
            elif field.default_factory is not None:
                data[name] = field.default_factory()  # type: ignore[call-arg]
            else:
                data[name] = _mock_val(field.annotation, name)

        return schema.model_validate(data)

    def _format_chat_contents(
        self, messages: list[ChatMessage], system_instruction: str | None = None
    ) -> tuple[list[types.Content], str | None]:
        """Convert list of ChatMessage objects to Gemini SDK types.Content objects."""
        if not messages:
            raise GeminiAdapterError("Chat messages list cannot be empty.")

        contents: list[types.Content] = []
        sys_instructions: list[str] = []
        if system_instruction:
            sys_instructions.append(system_instruction)

        for msg in messages:
            if msg.role == "system":
                sys_instructions.append(msg.content)
            else:
                role = "user" if msg.role not in ("user", "model") else msg.role
                contents.append(
                    types.Content(
                        role=role,
                        parts=[types.Part.from_text(text=msg.content)],
                    )
                )

        combined_sys = "\n\n".join(sys_instructions) if sys_instructions else None

        if not contents:
            contents = [types.Content(role="user", parts=[types.Part.from_text(text="Hello")])]

        return contents, combined_sys

    # -----------------------------------------------------------------------
    # Public Generation API
    # -----------------------------------------------------------------------

    def generate_text(
        self,
        prompt: str,
        system_instruction: str | None = None,
        temperature: float = 0.7,
        max_output_tokens: int | None = None,
    ) -> GeminiResponse:
        """Synchronously generate text response using Google Gemini."""
        if not prompt or not prompt.strip():
            raise GeminiAdapterError("Prompt cannot be empty.")
        if temperature < 0.0 or temperature > 2.0:
            raise GeminiConfigurationError("Temperature must be between 0.0 and 2.0.")

        if self.test_mode and self._client is None:
            return self._mock_text_response(prompt)

        config = types.GenerateContentConfig(
            temperature=temperature,
            system_instruction=system_instruction,
            max_output_tokens=max_output_tokens,
        )

        def _call() -> GeminiResponse:
            res = self._client.models.generate_content(
                model=self.model,
                contents=prompt,
                config=config,
            )
            return self._extract_response(res)

        return self._execute_with_retry_sync(_call)

    async def agenerate_text(
        self,
        prompt: str,
        system_instruction: str | None = None,
        temperature: float = 0.7,
        max_output_tokens: int | None = None,
    ) -> GeminiResponse:
        """Asynchronously generate text response using Google Gemini."""
        if not prompt or not prompt.strip():
            raise GeminiAdapterError("Prompt cannot be empty.")
        if temperature < 0.0 or temperature > 2.0:
            raise GeminiConfigurationError("Temperature must be between 0.0 and 2.0.")

        if self.test_mode and self._client is None:
            return self._mock_text_response(prompt)

        config = types.GenerateContentConfig(
            temperature=temperature,
            system_instruction=system_instruction,
            max_output_tokens=max_output_tokens,
        )

        async def _call() -> GeminiResponse:
            if hasattr(self._client, "aio") and hasattr(self._client.aio, "models"):
                res = self._client.aio.models.generate_content(
                    model=self.model,
                    contents=prompt,
                    config=config,
                )
                response = await res if inspect.isawaitable(res) else res
            else:
                res = self._client.models.generate_content(
                    model=self.model,
                    contents=prompt,
                    config=config,
                )
                response = await res if inspect.isawaitable(res) else res
            return self._extract_response(response)

        return await self._execute_with_retry_async(_call)

    def generate_structured(
        self,
        prompt: str,
        response_schema: type[ModelT],
        system_instruction: str | None = None,
        temperature: float = 0.2,
    ) -> ModelT:
        """Synchronously generate structured output adhering to a Pydantic schema."""
        if not prompt or not prompt.strip():
            raise GeminiAdapterError("Prompt cannot be empty.")
        if not (isinstance(response_schema, type) and issubclass(response_schema, BaseModel)):
            raise GeminiConfigurationError("response_schema must be a Pydantic BaseModel subclass.")
        if temperature < 0.0 or temperature > 2.0:
            raise GeminiConfigurationError("Temperature must be between 0.0 and 2.0.")

        if self.test_mode and self._client is None:
            return self._mock_structured_response(response_schema)

        config = types.GenerateContentConfig(
            temperature=temperature,
            system_instruction=system_instruction,
            response_mime_type="application/json",
            response_schema=response_schema,
        )

        def _call() -> ModelT:
            res = self._client.models.generate_content(
                model=self.model,
                contents=prompt,
                config=config,
            )
            return self._parse_structured_response(res, response_schema)

        return self._execute_with_retry_sync(_call)

